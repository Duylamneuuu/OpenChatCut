// Render the CutPilot Live launch film.
//
//   node scripts/render-cutpilot-promo.mjs
//   node scripts/render-cutpilot-promo.mjs --stills 108,500,900,1040
//
// Uses the Remotion packages already in this repo. Chrome is
// CC_BROWSER_EXECUTABLE or /opt/google/chrome/chrome when that binary exists.
import { bundle } from '@remotion/bundler';
import { renderMedia, renderStill, selectComposition } from '@remotion/renderer';
import { existsSync } from 'node:fs';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Fonts are inlined so a headless page does not fetch them while delayRender is open.
{
  const { writeFileSync, readFileSync } = await import('node:fs');
  const faces = [
    ['Geist', '400', 'public/fonts/Geist-Regular.woff2'],
    ['Geist', '600', 'public/fonts/Geist-SemiBold.woff2'],
    ['Geist', '700', 'public/fonts/Geist-Bold.woff2'],
    ['Ioskeley Mono', '500', 'public/fonts/IoskeleyMono-Medium.woff2'],
  ];
  const rows = faces.map(([family, weight, file]) => {
    const base64 = readFileSync(path.join(root, file)).toString('base64');
    return `  { family: ${JSON.stringify(family)}, weight: ${JSON.stringify(weight)}, base64: '${base64}' },`;
  });
  writeFileSync(path.join(root, 'promo', 'fonts.ts'), `// Generated by scripts/render-cutpilot-promo.mjs\nexport const PROMO_FONTS: ReadonlyArray<{ family: string; weight: string; base64: string }> = [\n${rows.join('\n')}\n];\n`);
}
const entry = path.join(root, 'promo', 'index.ts');
const publicDir = path.join(root, 'public');
const compositionId = 'IntroducingCutPilot';
const browserExecutable = process.env.CC_BROWSER_EXECUTABLE
  || (existsSync('/opt/google/chrome/chrome') ? '/opt/google/chrome/chrome' : undefined);

const stillsFlag = process.argv.find((arg) => arg.startsWith('--stills'));
const stillArg = stillsFlag?.includes('=')
  ? stillsFlag.split('=')[1]
  : (stillsFlag ? process.argv[process.argv.indexOf(stillsFlag) + 1] : '');
const stillFrames = stillArg ? stillArg.split(',').map((value) => Number(value)).filter((value) => Number.isFinite(value)) : [];
const videoOut = process.env.CUTPILOT_PROMO_OUT || '/opt/cursor/artifacts/cutpilot-promo.mp4';
const posterOut = process.env.CUTPILOT_PROMO_POSTER || '/opt/cursor/artifacts/cutpilot-promo-poster.png';

const serveUrl = await bundle({
  entryPoint: entry,
  publicDir,
  webpackOverride: (config) => ({
    ...config,
    resolve: {
      ...config.resolve,
      extensionAlias: {
        ...config.resolve?.extensionAlias,
        '.js': ['.js', '.ts', '.tsx'],
      },
    },
  }),
});

const composition = await selectComposition({
  serveUrl,
  id: compositionId,
  browserExecutable,
  chromiumOptions: { gl: 'angle-egl' },
});

const shared = {
  serveUrl,
  composition,
  browserExecutable,
  chromiumOptions: { gl: 'angle-egl' },
  concurrency: 1,
};

if (stillFrames.length) {
  for (const frame of stillFrames) {
    const output = path.join('/tmp/cutpilot-dl', `promo-frame-${frame}.png`);
    await mkdir(path.dirname(output), { recursive: true });
    await renderStill({ ...shared, frame, output, imageFormat: 'png' });
    console.log(`still ${frame} -> ${output}`);
  }
} else {
  await mkdir(path.dirname(videoOut), { recursive: true });
  await mkdir(path.dirname(posterOut), { recursive: true });
  // A fresh headless page calls delayRender while it decodes the inlined fonts.
  // On this Chrome build that call does not clear after the first ~400 frames,
  // so the film is rendered in short ranges and concatenated.
  const parts = [];
  const span = 300;
  for (let start = 0; start < composition.durationInFrames; start += span) {
    const end = Math.min(composition.durationInFrames - 1, start + span - 1);
    const part = `${videoOut}.part${String(start).padStart(4, '0')}.mp4`;
    parts.push(part);
    console.log(`range ${start}-${end}`);
    await renderMedia({
      ...shared,
      codec: 'h264',
      outputLocation: part,
      crf: 18,
      frameRange: [start, end],
    });
  }
  const list = `${videoOut}.concat.txt`;
  const { writeFileSync } = await import('node:fs');
  writeFileSync(list, parts.map((part) => `file '${part}'`).join('\n') + '\n');
  const { execFileSync } = await import('node:child_process');
  execFileSync('ffmpeg', ['-y', '-f', 'concat', '-safe', '0', '-i', list, '-c', 'copy', videoOut], { stdio: 'inherit' });
  console.log(`video -> ${videoOut}`);
  await renderStill({
    ...shared,
    frame: 1040,
    output: posterOut,
    imageFormat: 'png',
  });
  console.log(`poster -> ${posterOut}`);
}
