// Render the CutPilot Live launch film.
//
//   node scripts/render-cutpilot-promo.mjs
//   node scripts/render-cutpilot-promo.mjs --stills 40,120,230,280,450,860
//   node scripts/render-cutpilot-promo.mjs --music
//
// Writes a 1920×1080 film and a 1080×1080 cut. The stitched master mixes
// the Kokoro voiceover with ducked ticks and a quiet synthesized sine bed.
// --music lifts that bed. The white hold stays silent.
import { bundle } from '@remotion/bundler';
import { renderMedia, renderStill, selectComposition } from '@remotion/renderer';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fps = 30;
const frames = 900;
const sampleRate = 44100;

{
  const faces = [
    ['Geist', '400', 'public/fonts/Geist-Regular.woff2'],
    ['Geist', '600', 'public/fonts/Geist-SemiBold.woff2'],
    ['Geist', '700', 'public/fonts/Geist-Bold.woff2'],
    ['Ioskeley Mono', '500', 'public/fonts/IoskeleyMono-Medium.woff2'],
  ];
  const rows = faces.map(([family, weight, file]) => {
    const base64 = readFileSync(path.join(root, file)).toString('base64');
    return `  { family: ${JSON.stringify(family)}, weight: ${JSON.stringify(weight)}, base64: '${base64}' },`;
  });
  writeFileSync(
    path.join(root, 'promo', 'fonts.ts'),
    `// Generated by scripts/render-cutpilot-promo.mjs\nexport const PROMO_FONTS: ReadonlyArray<{ family: string; weight: string; base64: string }> = [\n${rows.join('\n')}\n];\n`,
  );
}

const timeline = readFileSync(path.join(root, 'promo', 'timeline.ts'), 'utf8');
const tickMatch = timeline.match(/export const TICK_FRAMES = \[([0-9,\s]+)\]/);
const tickFrames = tickMatch ? tickMatch[1].split(',').map((value) => Number(value.trim())).filter((value) => Number.isFinite(value)) : [];
if (!tickFrames.length) throw new Error('TICK_FRAMES missing from promo/timeline.ts');

function mixWav(music) {
  const count = sampleRate * (frames / fps);
  const data = new Float64Array(count);
  for (const frame of tickFrames) {
    const start = Math.floor((frame / fps) * sampleRate);
    const length = Math.floor(sampleRate * 0.028);
    for (let i = 0; i < length && start + i < count; i += 1) {
      const t = i / sampleRate;
      const env = Math.exp(-t * 160);
      data[start + i] += Math.sin(2 * Math.PI * 2100 * t) * env * 0.055;
    }
  }
  const bed = music ? 0.022 : 0.012;
  for (let i = 0; i < count; i += 1) {
    const frame = (i / sampleRate) * fps;
    if (frame >= 720 && frame < 780) continue;
    const t = i / sampleRate;
    const fade = Math.min(1, t / 0.6, (30 - t) / 0.8);
    data[i] += (Math.sin(2 * Math.PI * 98 * t) + Math.sin(2 * Math.PI * 196 * t) * 0.35) * bed * fade;
  }
  for (let i = 0; i < count; i += 1) {
    const frame = (i / sampleRate) * fps;
    if (frame >= 720 && frame < 780) data[i] = 0;
  }
  const buffer = Buffer.alloc(44 + count * 2);
  buffer.write('RIFF', 0);
  buffer.writeUInt32LE(36 + count * 2, 4);
  buffer.write('WAVE', 8);
  buffer.write('fmt ', 12);
  buffer.writeUInt32LE(16, 16);
  buffer.writeUInt16LE(1, 20);
  buffer.writeUInt16LE(1, 22);
  buffer.writeUInt32LE(sampleRate, 24);
  buffer.writeUInt32LE(sampleRate * 2, 28);
  buffer.writeUInt16LE(2, 32);
  buffer.writeUInt16LE(16, 34);
  buffer.write('data', 36);
  buffer.writeUInt32LE(count * 2, 40);
  for (let i = 0; i < count; i += 1) {
    const sample = Math.max(-1, Math.min(1, data[i]));
    buffer.writeInt16LE((sample * 32767) | 0, 44 + i * 2);
  }
  return buffer;
}

const audioDir = path.join(root, 'public', 'cutpilot');
await mkdir(audioDir, { recursive: true });
const voPath = path.join(audioDir, 'promo-vo.wav');
if (!existsSync(voPath)) throw new Error('Missing public/cutpilot/promo-vo.wav. Run npm run cutpilot:vo');
writeFileSync(path.join(audioDir, 'promo-ticks.wav'), mixWav(false));
writeFileSync(path.join(audioDir, 'promo-bed.wav'), mixWav(true));

const music = process.argv.includes('--music');
const entry = path.join(root, 'promo', 'index.ts');
const publicDir = path.join(root, 'public');
const browserExecutable = process.env.CC_BROWSER_EXECUTABLE
  || (existsSync('/opt/google/chrome/chrome') ? '/opt/google/chrome/chrome' : undefined);
const stillsFlag = process.argv.find((arg) => arg.startsWith('--stills'));
const stillArg = stillsFlag?.includes('=')
  ? stillsFlag.split('=')[1]
  : (stillsFlag ? process.argv[process.argv.indexOf(stillsFlag) + 1] : '');
const stillFrames = stillArg ? stillArg.split(',').map((value) => Number(value)).filter((value) => Number.isFinite(value)) : [];
const wideOut = process.env.CUTPILOT_PROMO_OUT || '/opt/cursor/artifacts/cutpilot-promo.mp4';
const squareOut = process.env.CUTPILOT_PROMO_SQUARE || '/opt/cursor/artifacts/cutpilot-promo-square.mp4';
const posterOut = process.env.CUTPILOT_PROMO_POSTER || '/opt/cursor/artifacts/cutpilot-promo-poster.png';

const serveUrl = await bundle({
  entryPoint: entry,
  publicDir,
  webpackOverride: (config) => ({
    ...config,
    resolve: {
      ...config.resolve,
      extensionAlias: {
        ...config.resolve?.extensionAlias,
        '.js': ['.js', '.ts', '.tsx'],
      },
    },
  }),
});

const chromiumOptions = { gl: 'angle-egl' };
const inputProps = { music };

async function loadComposition(id) {
  return selectComposition({
    serveUrl,
    id,
    browserExecutable,
    chromiumOptions,
    inputProps,
  });
}

const wide = await loadComposition('IntroducingCutPilot');
const square = await loadComposition('IntroducingCutPilotSquare');

async function still(composition, frame, output) {
  await mkdir(path.dirname(output), { recursive: true });
  await renderStill({
    serveUrl,
    composition,
    browserExecutable,
    chromiumOptions,
    inputProps,
    frame,
    output,
    imageFormat: 'png',
  });
  console.log(`still ${composition.id} ${frame} -> ${output}`);
}

async function video(composition, output) {
  await mkdir(path.dirname(output), { recursive: true });
  const parts = [];
  const span = 300;
  for (let start = 0; start < composition.durationInFrames; start += span) {
    const end = Math.min(composition.durationInFrames - 1, start + span - 1);
    const part = `${output}.part${String(start).padStart(4, '0')}.mp4`;
    parts.push(part);
    console.log(`${composition.id} ${start}-${end}`);
    await renderMedia({
      serveUrl,
      composition,
      browserExecutable,
      chromiumOptions,
      inputProps,
      codec: 'h264',
      outputLocation: part,
      crf: 17,
      concurrency: 1,
      frameRange: [start, end],
    });
  }
  const list = `${output}.concat.txt`;
  writeFileSync(list, parts.map((part) => `file '${part}'`).join('\n') + '\n');
  const joined = `${output}.joined.mp4`;
  execFileSync('ffmpeg', ['-y', '-f', 'concat', '-safe', '0', '-i', list, '-c', 'copy', joined], { stdio: 'inherit' });
  // The copy-concat leaves a timestamp gap at each range boundary, and each
  // part's AAC adds its own priming. Renumber the 900 pictures and replace
  // the audio with the master wav so the ticks stay on their frames.
  const masterAudio = path.join(audioDir, music ? 'promo-bed.wav' : 'promo-ticks.wav');
  // Each part's AAC adds its own priming, so the concatenated soundtrack is
  // discarded. The voiceover and the tick bed are mixed here, levels unchanged.
  execFileSync('ffmpeg', [
    '-y', '-i', joined, '-i', masterAudio, '-i', voPath,
    '-filter_complex', '[1:a][2:a]amix=inputs=2:duration=longest:normalize=0,aformat=sample_rates=48000:channel_layouts=stereo[a]',
    '-map', '0:v:0', '-map', '[a]',
    '-vf', 'setpts=N/30/TB',
    '-frames:v', String(composition.durationInFrames),
    '-fps_mode', 'passthrough',
    '-c:v', 'libx264',
    '-crf', '17',
    '-pix_fmt', 'yuv420p',
    '-c:a', 'aac',
    '-b:a', '192k',
    '-shortest',
    output,
  ], { stdio: 'inherit' });
  const probed = execFileSync('ffprobe', [
    '-v', 'error', '-select_streams', 'v:0',
    '-show_entries', 'stream=nb_frames,width,height,r_frame_rate,duration',
    '-of', 'json', output,
  ], { encoding: 'utf8' });
  const stream = JSON.parse(probed).streams[0];
  if (stream.nb_frames !== String(composition.durationInFrames) || stream.r_frame_rate !== '30/1') {
    throw new Error(`${output} came out ${stream.width}x${stream.height} ${stream.nb_frames} frames at ${stream.r_frame_rate} (${stream.duration}s)`);
  }
  for (const part of parts) execFileSync('rm', ['-f', part]);
  execFileSync('rm', ['-f', joined, list]);
  console.log(`video -> ${output} ${stream.width}x${stream.height} ${stream.nb_frames}f ${stream.duration}s`);
}

if (stillFrames.length) {
  const squareToo = process.argv.includes('--square');
  for (const frame of stillFrames) {
    const output = path.join('/tmp/cutpilot-dl', `promo-frame-${frame}.png`);
    await still(wide, frame, output);
    if (squareToo) await still(square, frame, output.replace('.png', '-square.png'));
  }
} else {
  if (!process.argv.includes('--square-only')) await video(wide, wideOut);
  await video(square, squareOut);
  await still(wide, 860, posterOut);
  const artifactFrames = [130, 280, 570, 860];
  for (const frame of artifactFrames) {
    await still(wide, frame, `/opt/cursor/artifacts/cutpilot-promo-f${String(frame).padStart(4, '0')}.png`);
  }
}
